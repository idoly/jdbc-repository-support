package io.github.idoly.jdbc.repository.testsupport;

import java.util.UUID;

import com.zaxxer.hikari.HikariDataSource;
import org.springframework.boot.autoconfigure.AutoConfigurations;
import org.springframework.boot.data.jdbc.autoconfigure.DataJdbcRepositoriesAutoConfiguration;
import org.springframework.boot.jdbc.autoconfigure.DataSourceAutoConfiguration;
import org.springframework.boot.jdbc.autoconfigure.DataSourceTransactionManagerAutoConfiguration;
import org.springframework.boot.jdbc.autoconfigure.JdbcClientAutoConfiguration;
import org.springframework.boot.jdbc.autoconfigure.JdbcTemplateAutoConfiguration;
import org.springframework.boot.test.context.runner.ApplicationContextRunner;
import org.springframework.boot.transaction.autoconfigure.TransactionAutoConfiguration;
import org.springframework.data.annotation.Id;
import org.springframework.data.relational.core.mapping.Table;
import org.springframework.data.repository.NoRepositoryBean;
import org.springframework.jdbc.core.simple.JdbcClient;

import io.github.idoly.jdbc.repository.JdbcRepository;
import io.github.idoly.jdbc.repository.config.JdbcClientRepositoryAutoConfiguration;

public final class JdbcTestSupport {

    private JdbcTestSupport() {
    }

    public static ApplicationContextRunner runner(Class<?>... configurations) {
        return new ApplicationContextRunner()
                .withConfiguration(AutoConfigurations.of(
                        DataSourceAutoConfiguration.class, JdbcTemplateAutoConfiguration.class,
                        JdbcClientAutoConfiguration.class, DataSourceTransactionManagerAutoConfiguration.class,
                        TransactionAutoConfiguration.class, DataJdbcRepositoriesAutoConfiguration.class,
                        JdbcClientRepositoryAutoConfiguration.class))
                .withUserConfiguration(configurations)
                .withPropertyValues("spring.datasource.generate-unique-name=true");
    }

    public static HikariDataSource dataSource(String name) {
        HikariDataSource source = new HikariDataSource();
        source.setJdbcUrl("jdbc:h2:mem:" + UUID.randomUUID());
        JdbcClient client = JdbcClient.create(source);
        createTable(client);
        client.sql("INSERT INTO sample VALUES (100, :name)").param("name", name).update();
        return source;
    }

    public static void createTable(JdbcClient client) {
        client.sql("""
                CREATE TABLE sample (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(50))
                """).update();
    }

    @NoRepositoryBean
    public interface SampleRepository extends JdbcRepository<Sample, Long> {

        default String findName(long id) {
            return sql("SELECT name FROM sample WHERE id = :id").param("id", id).query(String.class).single();
        }

        default long countRows() {
            return sql("SELECT COUNT(*) FROM sample").query(Long.class).single();
        }
    }

    @Table("SAMPLE")
    public record Sample(@Id Long id, String name) {
    }
}
